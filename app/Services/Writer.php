<?php

namespace App\Services;

use App\Enums\FactStatus;
use App\Enums\QuestionStatus;
use App\Enums\QuestionType;
use App\Enums\SectionCreatedBy;
use App\Enums\SectionType;
use App\Enums\SiteStatus;
use App\Models\AiRun;
use App\Models\Section;
use App\Models\SectionVersion;
use App\Models\Site;
use DomainException;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Throwable;

class Writer
{
    public function canGenerate(Site $site): bool
    {
        return ! $site->questions()
            ->where('status', QuestionStatus::Open)
            ->whereIn('type', [QuestionType::PickBusiness, QuestionType::ResolveConflict])
            ->exists();
    }

    public function generate(Site $site): bool
    {
        if (! $this->canGenerate($site)) {
            throw new DomainException('Please resolve open business selection or conflict questions before generating.');
        }

        $facts = $this->confirmedFactsPayload($site);
        $apiKey = (string) config('services.gemini.api_key');
        $model = (string) config('services.gemini.model', 'gemini-2.5-flash');

        if ($apiKey === '') {
            $this->logRun($site, 'write_site', 'failed', 'GEMINI_API_KEY is not configured.', 0);

            return false;
        }

        $template = (string) file_get_contents(resource_path('prompts/write_site.txt'));
        $prompt = str_replace(
            ['{{LANGUAGE}}', '{{DATA}}'],
            [$site->language ?: 'en', json_encode($facts, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE)],
            $template
        );

        $startedAt = hrtime(true);
        $maxAttempts = 3; // initial try + 2 retries
        $lastError = 'Unknown error';

        for ($attempt = 1; $attempt <= $maxAttempts; $attempt++) {
            try {
                $endpoint = "https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key={$apiKey}";

                $response = Http::timeout(30)->post($endpoint, [
                    'contents' => [
                        ['parts' => [['text' => $prompt]]],
                    ],
                    'generationConfig' => [
                        'responseMimeType' => 'application/json',
                    ],
                ]);

                if ($response->successful()) {
                    $jsonText = (string) $response->json('candidates.0.content.parts.0.text', '');
                    $decoded = json_decode($jsonText, true);

                    if ($this->isValidSchema($decoded)) {
                        $this->saveSections($site, $decoded, SectionCreatedBy::Ai, 'Generated by AI');
                        $durationMs = (int) ((hrtime(true) - $startedAt) / 1_000_000);
                        $this->logRun($site, 'write_site', 'success', null, $durationMs);

                        return true;
                    }

                    $lastError = 'AI returned invalid JSON schema.';
                } else {
                    $lastError = "HTTP {$response->status()} from AI service.";
                }
            } catch (Throwable $e) {
                $lastError = $e->getMessage();
                Log::warning('Writer Gemini attempt failed', [
                    'site_id' => $site->id,
                    'attempt' => $attempt,
                    'error' => $lastError,
                ]);
            }

            if ($attempt < $maxAttempts) {
                usleep(50_000 * $attempt);
            }
        }

        $durationMs = (int) ((hrtime(true) - $startedAt) / 1_000_000);
        $this->logRun($site, 'write_site', 'failed', $lastError, $durationMs);

        return false;
    }

    public function regenerate(Site $site, Section $section, ?string $instruction = null): bool
    {
        $type = $section->type->value;
        $purpose = "regenerate_{$type}";
        $facts = $this->confirmedFactsPayload($site);
        $apiKey = (string) config('services.gemini.api_key');
        $model = (string) config('services.gemini.model', 'gemini-2.5-flash');

        if ($apiKey === '') {
            $this->logRun($site, $purpose, 'failed', 'GEMINI_API_KEY is not configured.', 0);

            return false;
        }

        $schema = $this->sectionSchema($section->type);
        if ($schema === null) {
            return false;
        }

        $template = (string) file_get_contents(resource_path('prompts/regenerate_section.txt'));
        $prompt = str_replace(
            ['{{SECTION_TYPE}}', '{{LANGUAGE}}', '{{INSTRUCTION}}', '{{SCHEMA}}', '{{DATA}}'],
            [
                $type,
                $site->language ?: 'en',
                trim((string) $instruction) ?: 'None',
                $schema,
                json_encode($facts, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE),
            ],
            $template
        );

        $startedAt = hrtime(true);
        $maxAttempts = 3;
        $lastError = 'Unknown error';

        for ($attempt = 1; $attempt <= $maxAttempts; $attempt++) {
            try {
                $endpoint = "https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key={$apiKey}";

                $response = Http::timeout(30)->post($endpoint, [
                    'contents' => [
                        ['parts' => [['text' => $prompt]]],
                    ],
                    'generationConfig' => [
                        'responseMimeType' => 'application/json',
                    ],
                ]);

                if ($response->successful()) {
                    $jsonText = (string) $response->json('candidates.0.content.parts.0.text', '');
                    $decoded = json_decode($jsonText, true);
                    $normalized = $this->normalizeSectionContent($section->type, $decoded, $section->content ?? []);

                    if ($normalized !== null) {
                        $note = trim((string) $instruction) !== ''
                            ? 'Regenerated by AI: '.trim((string) $instruction)
                            : 'Regenerated by AI';

                        $version = SectionVersion::create([
                            'section_id' => $section->id,
                            'content' => $normalized,
                            'created_by' => SectionCreatedBy::Ai,
                            'note' => $note,
                        ]);

                        $section->update([
                            'content' => $normalized,
                            'current_version_id' => $version->id,
                        ]);

                        $durationMs = (int) ((hrtime(true) - $startedAt) / 1_000_000);
                        $this->logRun($site, $purpose, 'success', null, $durationMs);

                        return true;
                    }

                    $lastError = 'AI returned invalid section JSON.';
                } else {
                    $lastError = "HTTP {$response->status()} from AI service.";
                }
            } catch (Throwable $e) {
                $lastError = $e->getMessage();
                Log::warning('Writer regenerate attempt failed', [
                    'site_id' => $site->id,
                    'section_id' => $section->id,
                    'attempt' => $attempt,
                    'error' => $lastError,
                ]);
            }

            if ($attempt < $maxAttempts) {
                usleep(50_000 * $attempt);
            }
        }

        $durationMs = (int) ((hrtime(true) - $startedAt) / 1_000_000);
        $this->logRun($site, $purpose, 'failed', $lastError, $durationMs);

        return false;
    }

    private function sectionSchema(SectionType $type): ?string
    {
        return match ($type) {
            SectionType::Hero => '{"headline": "...", "subheadline": "..."}',
            SectionType::About => '{"heading": "...", "body": "..."}',
            SectionType::Services => '{"heading": "...", "items": [{"name": "...", "description": "..."}]}',
            SectionType::Contact => '{"heading": "...", "intro": "..."}',
            default => null,
        };
    }

    /**
     * @param array<string, mixed> $existing
     * @return array<string, mixed>|null
     */
    private function normalizeSectionContent(SectionType $type, mixed $data, array $existing): ?array
    {
        if (! is_array($data)) {
            return null;
        }

        return match ($type) {
            SectionType::Hero => (isset($data['headline'], $data['subheadline']) && is_string($data['headline']) && is_string($data['subheadline']))
                ? [
                    'headline' => $data['headline'],
                    'subheadline' => $data['subheadline'],
                    'seo_title' => $existing['seo_title'] ?? $data['headline'],
                    'seo_description' => $existing['seo_description'] ?? '',
                ]
                : null,
            SectionType::About => (isset($data['body']) && is_string($data['body']))
                ? [
                    'heading' => is_string($data['heading'] ?? null) ? $data['heading'] : ($existing['heading'] ?? 'About Us'),
                    'body' => $data['body'],
                ]
                : null,
            SectionType::Services => (isset($data['items']) && is_array($data['items']))
                ? [
                    'heading' => is_string($data['heading'] ?? null) ? $data['heading'] : ($existing['heading'] ?? 'Our Services'),
                    'items' => array_values(array_map(
                        fn ($item) => [
                            'name' => (string) ($item['name'] ?? ''),
                            'description' => (string) ($item['description'] ?? ''),
                        ],
                        $data['items']
                    )),
                ]
                : null,
            SectionType::Contact => (isset($data['intro']) && is_string($data['intro']))
                ? [
                    'heading' => is_string($data['heading'] ?? null) ? $data['heading'] : ($existing['heading'] ?? 'Contact Us'),
                    'intro' => $data['intro'],
                ]
                : null,
            default => null,
        };
    }

    public function buildBasicFallback(Site $site): void
    {
        $facts = $this->confirmedFactsPayload($site);

        $businessName = $facts['business_name'] ?? $site->business_name;
        $city = $facts['city'] ?? $site->city;
        $category = $facts['facts']['category'][0] ?? null;
        $aboutFacts = $facts['facts']['about_text'] ?? [];
        $services = $facts['facts']['service'] ?? [];

        $subheadlineParts = array_filter([$category, $city]);
        $aboutBody = $aboutFacts !== []
            ? implode("\n\n", $aboutFacts)
            : trim($businessName.($city ? " in {$city}." : '.'));

        $contactParts = [];
        foreach (['phone' => 'Phone', 'email' => 'Email', 'address' => 'Address', 'hours' => 'Hours'] as $key => $label) {
            if (! empty($facts['facts'][$key][0])) {
                $contactParts[] = "{$label}: {$facts['facts'][$key][0]}";
            }
        }

        $payload = [
            'seo' => [
                'title' => trim("{$businessName} - {$city}"),
                'description' => mb_substr($aboutBody, 0, 155),
            ],
            'hero' => [
                'headline' => $businessName,
                'subheadline' => implode(' • ', $subheadlineParts),
            ],
            'about' => [
                'heading' => 'About Us',
                'body' => $aboutBody,
            ],
            'services' => [
                'heading' => 'Services',
                'items' => array_map(
                    fn (string $s) => ['name' => $s, 'description' => ''],
                    $services
                ),
            ],
            'contact' => [
                'heading' => 'Contact',
                'intro' => $contactParts !== [] ? implode(' | ', $contactParts) : "Get in touch with {$businessName}.",
            ],
        ];

        $this->saveSections($site, $payload, SectionCreatedBy::User, 'Built without AI from confirmed facts');
    }

    /**
     * @return array<string, mixed>
     */
    protected function confirmedFactsPayload(Site $site): array
    {
        $confirmedFacts = $site->facts()
            ->whereIn('status', [FactStatus::Confirmed, FactStatus::UserProvided])
            ->get(['key', 'value']);

        $grouped = [];
        foreach ($confirmedFacts as $fact) {
            $grouped[$fact->key][] = $fact->value;
        }

        return [
            'business_name' => $grouped['business_name'][0] ?? $site->business_name,
            'city' => $site->city,
            'facts' => $grouped,
        ];
    }

    protected function isValidSchema(mixed $data): bool
    {
        if (! is_array($data)) {
            return false;
        }

        if (! isset($data['seo']['title'], $data['seo']['description'])
            || ! is_string($data['seo']['title'])
            || ! is_string($data['seo']['description'])) {
            return false;
        }

        if (! isset($data['hero']['headline'], $data['hero']['subheadline'])
            || ! is_string($data['hero']['headline'])
            || ! is_string($data['hero']['subheadline'])) {
            return false;
        }

        if (! isset($data['about']['body']) || ! is_string($data['about']['body'])) {
            return false;
        }

        if (! isset($data['services']['items']) || ! is_array($data['services']['items'])) {
            return false;
        }

        if (! isset($data['contact']['intro']) || ! is_string($data['contact']['intro'])) {
            return false;
        }

        return true;
    }

    /**
     * @param array<string, mixed> $payload
     */
    protected function saveSections(Site $site, array $payload, SectionCreatedBy $createdBy, string $note): void
    {
        $sectionsMap = [
            SectionType::Hero->value => [
                'headline' => (string) $payload['hero']['headline'],
                'subheadline' => (string) $payload['hero']['subheadline'],
                'seo_title' => (string) $payload['seo']['title'],
                'seo_description' => (string) $payload['seo']['description'],
            ],
            SectionType::About->value => [
                'heading' => (string) ($payload['about']['heading'] ?? 'About Us'),
                'body' => (string) $payload['about']['body'],
            ],
            SectionType::Services->value => [
                'heading' => (string) ($payload['services']['heading'] ?? 'Our Services'),
                'items' => array_values(array_map(
                    fn ($item) => [
                        'name' => (string) ($item['name'] ?? ''),
                        'description' => (string) ($item['description'] ?? ''),
                    ],
                    $payload['services']['items']
                )),
            ],
            SectionType::Contact->value => [
                'heading' => (string) ($payload['contact']['heading'] ?? 'Contact Us'),
                'intro' => (string) $payload['contact']['intro'],
            ],
        ];

        foreach ($sectionsMap as $type => $content) {
            $section = Section::updateOrCreate(
                ['site_id' => $site->id, 'type' => $type],
                ['content' => $content, 'is_visible' => true]
            );

            $version = SectionVersion::create([
                'section_id' => $section->id,
                'content' => $content,
                'created_by' => $createdBy,
                'note' => $note,
            ]);

            $section->update(['current_version_id' => $version->id]);
        }

        if ($site->status === SiteStatus::Draft) {
            $site->update(['status' => SiteStatus::Ready]);
        }
    }

    protected function logRun(Site $site, string $purpose, string $status, ?string $error, int $durationMs): void
    {
        AiRun::create([
            'site_id' => $site->id,
            'purpose' => $purpose,
            'status' => $status,
            'error' => $error,
            'duration_ms' => $durationMs,
        ]);
    }
}
