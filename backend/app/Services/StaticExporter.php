<?php

namespace App\Services;

use App\Models\Site;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Storage;
use RuntimeException;
use ZipArchive;

class StaticExporter
{
    public function __construct(
        protected SitePresenter $presenter,
    ) {
    }

    /**
     * Build a standalone static website ZIP archive and return its temporary path.
     */
    public function exportZip(Site $site): string
    {
        if (! class_exists(ZipArchive::class)) {
            throw new RuntimeException('PHP ZipArchive extension is required for static export.');
        }

        $data = $this->presenter->buildViewData($site, isPreview: false);
        $html = view('templates.' . $data['template'], $data)->render();

        $tempDir = storage_path('app/private/exports');
        File::ensureDirectoryExists($tempDir);

        $zipPath = $tempDir . '/' . $site->slug . '-' . uniqid('', true) . '.zip';
        $zip = new ZipArchive();

        if ($zip->open($zipPath, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
            throw new RuntimeException('Could not create export ZIP archive.');
        }

        // Rewrite asset URLs to local relative paths inside ZIP
        $exportHtml = $html;
        foreach ($data['photos'] as $photo) {
            $publicAssetUrl = asset('storage/' . $photo->path);
            $filename = basename($photo->path);
            $exportHtml = str_replace($publicAssetUrl, 'assets/' . $filename, $exportHtml);

            if (Storage::disk('public')->exists($photo->path)) {
                $zip->addFromString('assets/' . $filename, (string) Storage::disk('public')->get($photo->path));
            }
        }

        // Copy compiled CSS if available so offline viewing works seamlessly
        $manifestPath = public_path('build/manifest.json');
        if (file_exists($manifestPath)) {
            $manifest = json_decode((string) file_get_contents($manifestPath), true);
            $cssRel = $manifest['resources/css/app.css']['file'] ?? null;
            if ($cssRel && file_exists(public_path('build/' . $cssRel))) {
                $cssFile = basename($cssRel);
                $zip->addFromString('assets/' . $cssFile, (string) file_get_contents(public_path('build/' . $cssRel)));
                $exportHtml = str_replace(asset('build/' . $cssRel), 'assets/' . $cssFile, $exportHtml);
            }
        }

        $zip->addFromString('index.html', $exportHtml);
        $zip->addFromString('README.txt', implode("\n", [
            "{$site->business_name} — Static Website Export",
            'Generated by AI Builds My Website',
            '',
            'Upload the contents of this folder to Netlify, GitHub Pages, Vercel, or any web host.',
        ]));

        $zip->close();

        return $zipPath;
    }
}
